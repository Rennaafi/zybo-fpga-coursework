`timescale 1ns / 1ps

module alu_unit(
    input  wire [31:0] a,
    input  wire [31:0] b,
    input  wire [3:0]  sel,

    output reg  [31:0] result,
    output reg         zero
);

    always @(*) begin

        // Default values
        result = 32'b0;

        case (sel)

            // ====================================================
            // AND
            // ====================================================
            4'b0000:
                result = a & b;

            // ====================================================
            // OR
            // ====================================================
            4'b0001:
                result = a | b;

            // ====================================================
            // ADD
            // ====================================================
            4'b0010:
                result = a + b;

            // ====================================================
            // XOR
            // ====================================================
            4'b0011:
                result = a ^ b;

            // ====================================================
            // SLL - Shift Left Logical
            // ====================================================
            4'b0100:
                result = a << b[4:0];

            // ====================================================
            // SRL - Shift Right Logical
            // ====================================================
            4'b0101:
                result = a >> b[4:0];

            // ====================================================
            // SUB
            // ====================================================
            4'b0110:
                result = a - b;

            // ====================================================
            // SRA - Shift Right Arithmetic
            // ====================================================
            4'b0111:
                result = $signed(a) >>> b[4:0];

            // ====================================================
            // SLT - Set Less Than (SIGNED)
            // ====================================================
            4'b1000:
                result = ($signed(a) < $signed(b))
                         ? 32'd1
                         : 32'd0;

            // ====================================================
            // SLTU - Set Less Than Unsigned
            // ====================================================
            4'b1001:
                result = (a < b)
                         ? 32'd1
                         : 32'd0;

            // ====================================================
            // Default
            // ====================================================
            default:
                result = 32'b0;

        endcase

        // ========================================================
        // ZERO FLAG
        // ========================================================

        if (result == 32'b0)
            zero = 1'b1;
        else
            zero = 1'b0;

    end

endmodule